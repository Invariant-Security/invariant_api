# Sentinels invariant_assessment's _sshd_directive_value() writes into
# evidence_output when sshd -T couldn't be run -- see that function's
# docstring for why "absent" and "unknown" are kept distinct (a permission
# or config error must never be reported as "sshd not installed").
_SSHD_ABSENT_SENTINEL = "<sshd-not-installed>"
_SSHD_UNKNOWN_SENTINEL = "<sshd-status-unknown>"
_SSHD_EVIDENCE_PREFIX = "sshd_config:"


def ssh_state(findings: list[Finding]) -> str:
    """"present" | "absent" | "unknown" for this target's assessment run
    (always a single target per call -- every existing call site already
    passes one target's findings). Reads the explicit sentinel embedded in
    evidence_output; never inferred from classify_domain() (cosmetic,
    keyword-based, must never influence compliance) and never inferred
    from "every directive happened to be unset" (that could just as well
    mean the probe failed for an unrelated reason -- see _SSHD_UNKNOWN_
    SENTINEL). All sshd-directive evidence for one target comes from the
    same underlying probe, so the first one found is authoritative -- no
    need to require consensus across several.
    """
    for f in findings:
        if _SSHD_ABSENT_SENTINEL in f.evidence_output:
            return "absent"
        if _SSHD_UNKNOWN_SENTINEL in f.evidence_output:
            return "unknown"
        if f.evidence_output.startswith(_SSHD_EVIDENCE_PREFIX):
            return "present"
    return "present"  # no sshd evidence at all in this run -- never hide findings for lack of a signal
